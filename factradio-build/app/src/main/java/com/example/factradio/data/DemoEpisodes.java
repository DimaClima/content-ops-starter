    public static ArrayList<Episode> personalized(Context context) {
        PreferenceStore store = new PreferenceStore(context);
        ArrayList<Episode> episodes = new ArrayList<>();
        for (Episode episode : all()) {
            if (store.canPlayNow(episode)) episodes.add(episode);
        }
        Collections.shuffle(episodes);
        Collections.sort(episodes, Comparator.comparingInt(store::score).reversed());
        return episodes;
    }

