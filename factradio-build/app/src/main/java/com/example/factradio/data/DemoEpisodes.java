    private static List<DialogueLine> podcastDialogue(String opening, String script, String closing) {
        ArrayList<DialogueLine> lines = new ArrayList<>();
        lines.add(new DialogueLine(DialogueLine.MALE, opening));
        String[] paragraphs = script.split("\\n\\n+");
        for (int i = 0; i < paragraphs.length; i++) {
            String bridge;
            if (i == 0) bridge = "Начнём с фактов. ";
            else if (i == 1) bridge = "А вот здесь начинается самое интересное. ";
            else if (i == paragraphs.length - 1) bridge = "И к какому выводу мы приходим? ";
            else bridge = "Давай разберём следующий шаг. ";
            String speaker = i % 2 == 0 ? DialogueLine.FEMALE : DialogueLine.MALE;
            lines.add(new DialogueLine(speaker, bridge + paragraphs[i]));
        }
        lines.add(new DialogueLine(DialogueLine.FEMALE, closing));
        return lines;
    }
